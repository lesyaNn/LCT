"""P2-05 storage backends: production abstraction, Local impl, S3/MinIO seam.

The service layer talks ONLY to :class:`StorageBackend`; switching
Local -> S3/MinIO is a settings change (``STORAGE_BACKEND=s3``), never a
service rewrite. Physical object names are random UUID hex keys — the
original filename never appears in any path.
"""

from __future__ import annotations

import os
import re
import tempfile
import uuid
from abc import ABC, abstractmethod
from collections.abc import Iterable, Iterator
from contextlib import contextmanager
from functools import lru_cache
from pathlib import Path
from typing import BinaryIO

from fastapi import HTTPException
from app.core.errors import BusinessException

from app.config import settings

_KEY_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.\-]{0,200}")


def new_storage_key() -> str:
    """Random physical object name (no original filename inside)."""
    return uuid.uuid4().hex


class StorageError(Exception):
    """Generic storage failure (mapped to a controlled 5xx, never a leak)."""


class StorageNotConfigured(StorageError):
    """Backend selected but its credentials/endpoint are missing."""


class StorageObjectNotFound(StorageError, FileNotFoundError):
    """Physical object absent while metadata exists (controlled error)."""


def _checked_key(key: str) -> str:
    # Defense in depth: keys are generated by new_storage_key(); anything
    # path-like (``../``, slashes, drive letters) is rejected before IO.
    if not isinstance(key, str) or _KEY_RE.fullmatch(key) is None:
        raise StorageError("Invalid storage key")
    if ".." in key or "/" in key or "\\" in key or ":" in key:
        raise StorageError("Invalid storage key")
    return key


class StorageBackend(ABC):
    """Minimal production interface for workflow file objects."""

    @abstractmethod
    def save_stream(self, key: str, chunks: Iterable[bytes]) -> int:
        """Persist chunks under ``key`` atomically; return bytes written."""

    @abstractmethod
    @contextmanager
    def open_stream(self, key: str) -> Iterator[BinaryIO]:
        """Yield a binary read handle; missing object -> StorageObjectNotFound."""

    @abstractmethod
    def delete(self, key: str) -> None:
        """Remove the object; missing object -> StorageObjectNotFound."""

    @abstractmethod
    def exists(self, key: str) -> bool:
        """True when the object is present (never raises for missing)."""


class LocalStorageBackend(StorageBackend):
    """Filesystem backend rooted at ``root`` (production: ``/app/storage``).

    Atomicity: stream to ``.tmp/<key>.part-<rand>``, then ``os.replace``
    to the final name. Oversize/DB failures remove temp + final artefacts.
    """

    def __init__(self, root: str | Path) -> None:
        self._root = Path(root)
        self._tmp = self._root / ".tmp"
        # Default modes only (dir 755/file 644 under a normal umask);
        # never chmod 777.
        self._root.mkdir(parents=True, exist_ok=True)
        self._tmp.mkdir(parents=True, exist_ok=True)

    @property
    def root(self) -> Path:
        return self._root

    def _path_for(self, key: str) -> Path:
        return self._root / _checked_key(key)

    def save_stream(self, key: str, chunks: Iterable[bytes]) -> int:
        _checked_key(key)
        tmp_path = self._tmp / f"{key}.part-{uuid.uuid4().hex}"
        total = 0
        try:
            with open(tmp_path, "wb") as fh:
                for chunk in chunks:
                    if not chunk:
                        continue
                    fh.write(chunk)
                    total += len(chunk)
            os.replace(tmp_path, self._path_for(key))
        except Exception:
            for path in (tmp_path, self._root / key):
                try:
                    os.unlink(path)
                except OSError:
                    pass
            raise
        return total

    @contextmanager
    def open_stream(self, key: str) -> Iterator[BinaryIO]:
        path = self._path_for(key)
        try:
            fh = open(path, "rb")
        except FileNotFoundError:
            raise StorageObjectNotFound(f"Storage object missing: {key}") from None
        except OSError as exc:
            raise StorageError(str(exc)) from exc
        try:
            yield fh
        finally:
            fh.close()

    def delete(self, key: str) -> None:
        path = self._path_for(key)
        try:
            os.unlink(path)
        except FileNotFoundError:
            raise StorageObjectNotFound(f"Storage object missing: {key}") from None
        except OSError as exc:
            raise StorageError(str(exc)) from exc

    def exists(self, key: str) -> bool:
        try:
            return self._path_for(key).is_file()
        except StorageError:
            return False


class S3StorageBackend(StorageBackend):
    """MinIO/S3 seam: same interface, remote object store underneath.

    ``save_stream`` still streams chunk-by-chunk (into a bounded temp file,
    at most the 50 MiB upload limit) and then uploads — the service code
    path is identical to Local. Requires the ``minio`` package plus
    endpoint/credentials/bucket; otherwise every operation raises
    :class:`StorageNotConfigured` instead of failing obscurely.
    """

    def __init__(
        self,
        *,
        endpoint: str = "",
        access_key: str = "",
        secret_key: str = "",
        bucket: str = "",
        secure: bool = False,
        prefix: str = "workflow/",
    ) -> None:
        self._endpoint = (endpoint or "").strip()
        self._access_key = access_key or ""
        self._secret_key = secret_key or ""
        self._bucket = bucket or ""
        self._secure = secure
        self._prefix = prefix
        self._client = None

    def _configured(self) -> bool:
        return bool(self._endpoint and self._access_key and self._secret_key and self._bucket)

    def _connect(self):
        if self._client is not None:
            return self._client
        if not self._configured():
            raise StorageNotConfigured(
                "S3 storage selected but endpoint/credentials/bucket missing"
            )
        try:
            from urllib.parse import urlparse

            from minio import Minio
        except ImportError as exc:
            raise StorageNotConfigured("minio package not installed") from exc
        host = urlparse(self._endpoint).netloc or self._endpoint
        client = Minio(
            host,
            access_key=self._access_key,
            secret_key=self._secret_key,
            secure=self._secure or urlparse(self._endpoint).scheme == "https",
        )
        if not client.bucket_exists(self._bucket):
            client.make_bucket(self._bucket)
        self._client = client
        return client

    def _object(self, key: str) -> str:
        return f"{self._prefix}{_checked_key(key)}"

    def save_stream(self, key: str, chunks: Iterable[bytes]) -> int:
        client = self._connect()
        name = self._object(key)
        total = 0
        fd, tmp_name = tempfile.mkstemp(prefix="wf-upload-")
        try:
            with os.fdopen(fd, "wb") as fh:
                for chunk in chunks:
                    if not chunk:
                        continue
                    fh.write(chunk)
                    total += len(chunk)
            client.fput_object(self._bucket, name, tmp_name)
        except StorageError:
            raise
        except Exception as exc:
            # HTTP control flow (e.g. 413 from the chunk generator) passes
            # through unwrapped; only real failures become StorageError.
            if isinstance(exc, (HTTPException, BusinessException)):
                raise
            raise StorageError(str(exc)) from exc
        finally:
            try:
                os.unlink(tmp_name)
            except OSError:
                pass
        return total

    @contextmanager
    def open_stream(self, key: str) -> Iterator[BinaryIO]:
        client = self._connect()
        try:
            response = client.get_object(self._bucket, self._object(key))
        except Exception as exc:
            if exc.__class__.__name__ in ("NoSuchKey", "NoSuchBucket", "S3Error") and (
                "NoSuchKey" in str(exc) or "does not exist" in str(exc).lower()
            ):
                raise StorageObjectNotFound(f"Storage object missing: {key}") from None
            raise StorageError(str(exc)) from exc
        try:
            yield response
        finally:
            try:
                response.close()
                response.release_conn()
            except Exception:
                pass

    def delete(self, key: str) -> None:
        client = self._connect()
        name = self._object(key)
        try:
            client.stat_object(self._bucket, name)
        except Exception:
            raise StorageObjectNotFound(f"Storage object missing: {key}") from None
        try:
            client.remove_object(self._bucket, name)
        except Exception as exc:
            raise StorageError(str(exc)) from exc

    def exists(self, key: str) -> bool:
        try:
            self._connect().stat_object(self._bucket, self._object(key))
        except Exception:
            return False
        return True


# Backwards-compatible alias (MinIO speaks the S3 API).
MinioStorageBackend = S3StorageBackend


@lru_cache(maxsize=8)
def _cached_build(backend: str, root: str, endpoint: str, bucket: str) -> StorageBackend:
    if backend == "s3":
        return S3StorageBackend(
            endpoint=endpoint,
            access_key=settings.s3_access_key,
            secret_key=settings.s3_secret_key,
            bucket=bucket or settings.s3_bucket,
        )
    return LocalStorageBackend(root or settings.storage_root)


def build_storage_backend(
    *,
    backend: str | None = None,
    root: str | Path | None = None,
    endpoint: str | None = None,
    bucket: str | None = None,
) -> StorageBackend:
    """Factory: Local by default; S3/MinIO without touching the service."""
    name = (backend or settings.storage_backend or "local").lower()
    if name in ("s3", "minio"):
        return _cached_build(
            "s3", "", endpoint or settings.s3_endpoint, bucket or settings.s3_bucket
        )
    return _cached_build("local", str(root or settings.storage_root), "", "")
